/** Resolve catalogue ids to entries, silently dropping any that no longer exist. */
export function resolveResources(ids: string[] | undefined): Resource[] {
  if (!ids) return []
  return ids.map((id) => resources[id]).filter((r): r is Resource => Boolean(r))
}

