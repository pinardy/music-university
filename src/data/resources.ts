import type { Resource, ResourceKind } from '../types'

/**
 * Catalogue of external sources referenced by courses and lessons.
 *
 * Every URL here was checked as reachable when the catalogue was assembled.
 * Entries marked `open: false` are legitimate scholarly sources that normally
 * need a library or institutional login — they are listed because a conservatory
 * student will have that access, not as a paywall recommendation.
 *
 * Lessons and courses refer to entries by id; see `resolveResources`.
 */

type Seed = Omit<Resource, 'id'>

const OMT = 'https://viva.pressbooks.pub/openmusictheory/chapter/'
const MT21C = 'https://musictheory.pugetsound.edu/mt21c/'
const FFF = 'https://milnepublishing.geneseo.edu/fundamentals-function-form/chapter/'
const IMSLP = 'https://imslp.org/wiki/'
const LIBRETEXTS =
  'https://human.libretexts.org/Bookshelves/Music/Music_Appreciation/Understanding_Music_-_Past_and_Present_(Clark_et_al.)/'
const CONDUCTIT = 'https://conductit.eu/'

/** Open Music Theory v2, ed. Mark Gotham et al. (VIVA / Pressbooks, CC BY-SA). */
function omt(slug: string, title: string, note?: string): Seed {
  return { title, source: 'Open Music Theory (2nd ed.)', url: `${OMT}${slug}/`, kind: 'textbook', note, open: true }
}

/** Robert Hutchinson, Music Theory for the 21st-Century Classroom (CC BY-NC-SA). */
function mt21c(page: string, title: string, note?: string): Seed {
  return {
    title,
    source: 'Hutchinson, Music Theory for the 21st-Century Classroom',
    url: `${MT21C}${page}`,
    kind: 'textbook',
    note,
    open: true,
  }
}

/** Andre Mount, Fundamentals, Function, and Form (SUNY Geneseo / Milne, CC BY-NC-SA). */
function fff(slug: string, title: string, note?: string): Seed {
  return {
    title,
    source: 'Mount, Fundamentals, Function, and Form',
    url: `${FFF}${slug}/`,
    kind: 'textbook',
    note,
    open: true,
  }
}

/** IMSLP / Petrucci Music Library public-domain score page. */
function score(path: string, title: string, note?: string): Seed {
  return { title, source: 'IMSLP / Petrucci Music Library', url: `${IMSLP}${path}`, kind: 'score', note, open: true }
}

/** An out-of-copyright treatise, catalogued as a primary source rather than a score. */
function treatise(path: string, title: string, note?: string): Seed {
  return { title, source: 'IMSLP / Petrucci Music Library', url: `${IMSLP}${path}`, kind: 'primary', note, open: true }
}

/** Understanding Music: Past and Present (Clark et al., CC BY-SA) on LibreTexts. */
function um(path: string, title: string, note?: string): Seed {
  return {
    title,
    source: 'Clark et al., Understanding Music: Past and Present',
    url: `${LIBRETEXTS}${path}`,
    kind: 'textbook',
    note,
    open: true,
  }
}

/** ConductIT — open conducting curriculum (RNCM / Stavanger / Aveiro / Open University). */
function conductit(path: string, title: string, note?: string): Seed {
  return { title, source: 'ConductIT', url: `${CONDUCTIT}${path}`, kind: 'textbook', note, open: true }
}

function wiki(slug: string, title: string, note?: string): Seed {
  return { title, source: 'Wikipedia', url: `https://en.wikipedia.org/wiki/${slug}`, kind: 'reference', note, open: true }
}

